local function fluidName(item)
    local fc = item:getFluidContainerFromSelfOrWorldItem()
    return fc and fc:getPrimaryFluid() and tostring(fc:getPrimaryFluid():getFluidTypeString()) or "-"
end

local function sortedUnique(list)
    local seen, out = {}, {}
    for _, v in ipairs(list) do if not seen[v] then seen[v] = true; out[#out + 1] = v end end
    table.sort(out)
    return out
end

CZM_TEST_SUITES.perishable_time = function(t)
    local PF = PerishableFoods
    local ctx = { foods = {}, drinks = {}, elapsed = 0 }

    local function evaluate(label)
        local badFood, badDrink, firstBad = 0, 0, nil
        for _, f in ipairs(ctx.foods) do
            f.item:updateAge()
            local age = f.item:getAge()
            local okAge = math.abs(age - ctx.elapsed) < 0.25
            local okRotten = f.item:isRotten() == (ctx.elapsed >= f.rotten)
            local okFresh = f.item:isFresh() == (ctx.elapsed < f.fresh)
            if not (okAge and okRotten and okFresh) then
                badFood = badFood + 1
                firstBad = firstBad or string.format("%s age=%.2f rotten=%s fresh=%s (fresh %d, rotten %d)", f.name, age,
                    tostring(f.item:isRotten()), tostring(f.item:isFresh()), f.fresh, f.rotten)
            end
        end
        for _, d in ipairs(ctx.drinks) do
            PF.ageDrink(d.item, false)
            local spoiled = fluidName(d.item) == "SpoiledDrink"
            local okAge = d.spoiled or math.abs((d.item:getModData().PF_age or -1) - ctx.elapsed) < 0.25
            if spoiled then d.spoiled = true end
            if spoiled ~= (ctx.elapsed >= d.days) or not okAge then
                badDrink = badDrink + 1
                firstBad = firstBad or string.format("%s spoiled=%s age=%s (limit %d)", d.name, tostring(spoiled),
                    tostring(d.item:getModData().PF_age), d.days)
            end
        end
        t.check(string.format("day %d: %d foods and %d drinks match their table", ctx.elapsed, #ctx.foods, #ctx.drinks),
            badFood == 0 and badDrink == 0, firstBad and ("first mismatch: " .. firstBad) or nil)
    end

    t.queue(1, function()
        local inv = getSpecificPlayer(0):getInventory()
        ctx.t0 = PF.worldDays()
        for _, e in ipairs(PF.SCHEDULE) do
            local item = instanceItem(e[1])
            if item then
                inv:AddItem(item)
                PF.patchItem(item, false)
                ctx.foods[#ctx.foods + 1] = { item = item, name = e[1], fresh = e[2], rotten = e[3] }
            end
        end
        for name, e in pairs(PF.DRINKS) do
            local item = instanceItem(name)
            if item then
                inv:AddItem(item)
                PF.ageDrink(item, false)
                ctx.drinks[#ctx.drinks + 1] = { item = item, name = name, days = e[1] }
            end
        end
        local scheduled = 0
        for _ in ipairs(PF.SCHEDULE) do scheduled = scheduled + 1 end
        local drinkCount = 0
        for _ in pairs(PF.DRINKS) do drinkCount = drinkCount + 1 end
        t.check("every scheduled food item exists in game", #ctx.foods == scheduled, string.format("%d of %d", #ctx.foods, scheduled))
        t.check("every scheduled drink exists in game", #ctx.drinks == drinkCount, string.format("%d of %d", #ctx.drinks, drinkCount))
        local bad, first = 0, nil
        for _, f in ipairs(ctx.foods) do
            if f.item:getOffAge() ~= f.fresh or f.item:getOffAgeMax() ~= f.rotten then
                bad = bad + 1
                first = first or f.name
            end
        end
        t.check("every food starts with the table's fresh and rotten days", bad == 0, first and ("first: " .. first) or nil)
        evaluate("start")
    end)

    -- Check just before and just after every threshold in the tables.
    local marks = {}
    for _, e in ipairs(PF.SCHEDULE) do marks[#marks + 1] = e[2]; marks[#marks + 1] = e[3] end
    for _, e in pairs(PF.DRINKS) do marks[#marks + 1] = e[1] end
    for _, mark in ipairs(sortedUnique(marks)) do
        for _, offset in ipairs({ -1, 1 }) do
            t.queue(1, function()
                local target = mark + offset
                t.jumpDays(target - ctx.elapsed)
                ctx.elapsed = target
                -- the real elapsed time, from the game clock
                local real = PF.worldDays() - ctx.t0
                ctx.elapsed = math.floor(real + 0.5)
                evaluate()
            end)
        end
    end

    -- Things that must never spoil, even after more than a year.
    t.queue(1, function()
        t.jumpDays(450 - ctx.elapsed)
        ctx.elapsed = math.floor((PF.worldDays() - ctx.t0) + 0.5)
        local bad, first = 0, nil
        for _, name in ipairs(PF.NEVER_FOODS) do
            local item = instanceItem(name)
            if item then
                PF.patchItem(item, false)
                item:updateAge()
                if item:getOffAge() < 1000000000 or item:isRotten() then bad = bad + 1; first = first or name end
            end
        end
        t.check(string.format("%d never-spoil foods (sugar, salt, spices...) are intact after %d days", #PF.NEVER_FOODS, ctx.elapsed), bad == 0, first and ("first: " .. first) or nil)
        bad, first = 0, nil
        for _, name in ipairs(PF.NEVER_DRINKS) do
            local item = instanceItem(name)
            if item then
                local before = fluidName(item)
                PF.ageDrink(item, true)
                PF.ageDrink(item, false)
                if fluidName(item) ~= before or item:getModData().PF_t ~= nil then bad = bad + 1; first = first or name end
            end
        end
        t.check(string.format("%d never-spoil drinks (sealed alcohol, syrups) are intact", #PF.NEVER_DRINKS), bad == 0, first and ("first: " .. first) or nil)
        for _, name in ipairs({ "Base.CannedCorn", "Base.CannedPeas", "Base.CannedPeaches", "Base.CannedCornedBeef", "Base.TunaTin", "Base.TinnedBeans", "Base.TinnedSoup", "Base.CornSeed", "Base.CigaretteRolled" }) do
            local sc = getScriptManager():getItem(name)
            t.check("canned/non-food item untouched: " .. name, sc ~= nil and sc:getDaysFresh() >= 1000000000)
        end
        t.finish()
    end)
end

