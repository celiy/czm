CZM_TEST_SUITES.perishable_world = function(t)
    local PF = PerishableFoods
    local ctx = {}

    t.queue(1, function()
        local player = getSpecificPlayer(0)
        local px, py, pz = math.floor(player:getX()), math.floor(player:getY()), math.floor(player:getZ())
        local cell = getCell()
        for dx = -40, 40 do
            for dy = -40, 40 do
                if not ctx.cont then
                    local sq = cell:getGridSquare(px + dx, py + dy, pz)
                    if sq then
                        local objs = sq:getObjects()
                        for i = 0, objs:size() - 1 do
                            local c = objs:get(i):getContainer()
                            if c and not ctx.cont and not c:isFridge() and not c:isFreezer() then ctx.cont = c end
                        end
                    end
                end
            end
        end
        t.check("a world container exists near the spawn", ctx.cont ~= nil)
        if not ctx.cont then t.finish() return end
        t.jumpDays(40) -- time already passed in this world
        -- loot that the game fills into a container for the first time
        ctx.biscuit = instanceItem("Base.CookiesOatmeal")
        ctx.choc = instanceItem("Base.Chocolate")
        ctx.milk = instanceItem("Base.Milk")
        ctx.pop = instanceItem("Base.Pop")
        for _, it in ipairs({ ctx.biscuit, ctx.choc, ctx.milk, ctx.pop }) do ctx.cont:AddItem(it) end
        triggerEvent("OnFillContainer", "test", "crate", ctx.cont) -- the real game event, handled by the mod
        local age = PF.worldGeneratedAge()
        t.check("loot filled by the game is aged by the world's time", age > 38 and math.abs(ctx.biscuit:getAge() - age) < 0.5,
            string.format("biscuit age=%.2f world age=%.2f", ctx.biscuit:getAge(), age))
        t.check("filled biscuit (limit 45) is not rotten yet at day 40", not ctx.biscuit:isRotten())
        t.check("filled chocolate is fresh", ctx.choc:isFresh())
        t.check("filled milk is still good at day 40 (limit 60)", fluidName(ctx.milk) == "CowMilk", fluidName(ctx.milk))
        ctx.biscuit:updateAge()
    end)
    t.queue(1, function()
        PF.ageDrink(ctx.milk, false)
        t.jumpDays(10)
        ctx.biscuit:updateAge()
        PF.ageDrink(ctx.milk, false)
        t.check("50 days in: biscuit (limit 45) is rotten", ctx.biscuit:isRotten(), string.format("age=%.2f", ctx.biscuit:getAge()))
        t.check("50 days in: milk (limit 60) is still good", fluidName(ctx.milk) == "CowMilk", fluidName(ctx.milk))
        t.jumpDays(15)
        PF.ageDrink(ctx.milk, false)
        t.check("65 days in: milk is past its 60 days", fluidName(ctx.milk) == "SpoiledDrink", fluidName(ctx.milk))
        t.check("pop (365) is still good", fluidName(ctx.pop) ~= "SpoiledDrink")
    end)

    -- the player comes back to something that was lying there before the mod saw it
    t.queue(1, function()
        local old = instanceItem("Base.CookiesOatmeal")
        old:setAge(300)
        ctx.cont:AddItem(old)
        PF.processContainer(ctx.cont, false) -- what opening the container does
        t.check("old item seen on return starts fresh, not rotten", old:getAge() == 0 and not old:isRotten(), string.format("age=%.2f", old:getAge()))
        ctx.returned = old
    end)
    t.queue(1, function()
        t.jumpDays(46)
        ctx.returned:updateAge()
        t.check("then it spoils on schedule (46 days > 45)", ctx.returned:isRotten(), string.format("age=%.2f", ctx.returned:getAge()))
    end)

    -- adding the mod to an existing save: nothing is aged retroactively
    t.queue(1, function()
        local data = ModData.getOrCreate("PerishableFoods")
        data.origin = nil
        PF._origin = nil
        local day = PF.originDay()
        t.check("mod added mid-save: the clock starts that day", math.abs(day - PF.effectiveDay()) < 0.01,
            string.format("origin=%.2f today=%.2f", day, PF.effectiveDay()))
        t.check("mod added mid-save: world-generated age is 0", PF.worldGeneratedAge() < 0.01)
        local fresh = instanceItem("Base.CookiesOatmeal")
        PF.patchItem(fresh, true)
        t.check("mod added mid-save: unvisited loot is not aged retroactively", fresh:getAge() < 0.01, string.format("age=%.2f", fresh:getAge()))
        t.finish()
    end)
end

----------------------------------------------------------------------------
-- A game that starts months after the apocalypse
----------------------------------------------------------------------------

CZM_TEST_SUITES.perishable_apo = function(t)
    local PF = PerishableFoods
    t.queue(1, function()
        local months = getSandboxOptions():getTimeSinceApo() - 1
        t.check("this world started months after the apocalypse", months >= 3, string.format("months=%d", months))
        t.check("new game: the clock starts at the apocalypse", PF.originDay() == 0, tostring(PF.originDay()))
        local age = PF.worldGeneratedAge()
        t.check("world age includes those months", math.abs(age - months * 30) < 2, string.format("age=%.1f", age))

        local function made(name) local i = instanceItem(name); PF.processItem(i, true); return i end
        local biscuit, choc, cereal, milk, pop, juice, wineOpen, wine = made("Base.CookiesOatmeal"), made("Base.Chocolate"),
            made("Base.Cereal"), made("Base.Milk"), made("Base.Pop"), made("Base.JuiceOrange"), made("Base.WineOpen"), made("Base.Wine")
        t.check("loot at the start: biscuits (30 days) are rotten", biscuit:isRotten(), string.format("age=%.1f", biscuit:getAge()))
        t.check("loot at the start: cereal (180 days) is still fresh", cereal:isFresh() or not cereal:isRotten(), string.format("age=%.1f", cereal:getAge()))
        t.check("loot at the start: chocolate (1 year) is fresh", choc:isFresh(), string.format("age=%.1f", choc:getAge()))
        t.check("loot at the start: milk (60 days) has spoiled", fluidName(milk) == "SpoiledDrink", fluidName(milk))
        t.check("loot at the start: juice (30 days) has spoiled", fluidName(juice) == "SpoiledDrink", fluidName(juice))
        t.check("loot at the start: opened wine has spoiled", fluidName(wineOpen) == "SpoiledDrink", fluidName(wineOpen))
        t.check("loot at the start: pop (1 year) is fine", fluidName(pop) ~= "SpoiledDrink", fluidName(pop))
        t.check("loot at the start: sealed wine is fine", fluidName(wine) == "Wine", fluidName(wine))
        t.finish()
    end)
end
