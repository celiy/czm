CZM_TEST_SUITES = CZM_TEST_SUITES or {}

local function describe(TAG, fullType)
    local ok, item = pcall(instanceItem, fullType)
    if not ok or not item then
        print(TAG .. "probe " .. fullType .. " NOT AVAILABLE")
        return
    end
    local isFood = instanceof(item, "Food")
    local fc = item:getFluidContainer()
    local fluid = fc and fc:getPrimaryFluid() and tostring(fc:getPrimaryFluid():getFluidTypeString()) or "-"
    local line = string.format("%sprobe %s food=%s fluid=%s", TAG, fullType, tostring(isFood), fluid)
    if isFood then
        line = line .. string.format(" offAge=%s offAgeMax=%s age=%.2f", tostring(item:getOffAge()), tostring(item:getOffAgeMax()), item:getAge())
    end
    local si = getScriptManager():getItem(fullType)
    if si then line = line .. string.format(" scriptDaysFresh=%s scriptRotten=%s", tostring(si:getDaysFresh()), tostring(si:getDaysTotallyRotten())) end
    print(line)
end

