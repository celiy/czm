CZM_TEST_SUITES.perishable_fridge = function(t)
    local PF = PerishableFoods
    local ctx = {}

    -- look for real fridges and freezers around the spawn
    t.queue(1, function()
        local player = getSpecificPlayer(0)
        local px, py, pz = math.floor(player:getX()), math.floor(player:getY()), math.floor(player:getZ())
        local cell = getCell()
        local found = { fridge = nil, freezer = nil }
        for dx = -90, 90 do
            for dy = -90, 90 do
                local sq = cell:getGridSquare(px + dx, py + dy, pz)
                if sq then
                    local objs = sq:getObjects()
                    for i = 0, objs:size() - 1 do
                        local o = objs:get(i)
                        local c = o:getContainer()
                        if c and c.isFridge and c:isFridge() and not found.fridge then found.fridge = c end
                        if c and c.isFreezer and c:isFreezer() and not found.freezer then found.freezer = c end
                        for idx = 0, (o:getContainerCount() or 1) - 1 do
                            local cc = o:getContainerByIndex(idx)
                            if cc and cc:isFridge() and not found.fridge then found.fridge = cc end
                            if cc and cc:isFreezer() and not found.freezer then found.freezer = cc end
                        end
                    end
                end
            end
        end
        ctx.fridge, ctx.freezer = found.fridge, found.freezer
        print(string.format("%sdiag fridge found=%s freezer found=%s", t.TAG, tostring(ctx.fridge ~= nil), tostring(ctx.freezer ~= nil)))
        t.check("a real fridge exists near the spawn", ctx.fridge ~= nil)
        t.check("a real freezer exists near the spawn", ctx.freezer ~= nil)
        if ctx.fridge then
            t.check("fridge container reports a fridge", ctx.fridge:isFridge())
            t.check("fridge has power by the vanilla rule", PF.hasPower(ctx.fridge))
        end

        -- three places: room (player inventory), fridge, freezer
        ctx.places = { { name = "room", cont = player:getInventory(), expect = 1 } }
        if ctx.fridge then ctx.places[#ctx.places + 1] = { name = "fridge", cont = ctx.fridge, expect = PF.fridgeFactor() } end
        if ctx.freezer then ctx.places[#ctx.places + 1] = { name = "freezer", cont = ctx.freezer, expect = 0 } end
        ctx.t0 = PF.worldDays()
        for _, p in ipairs(ctx.places) do
            p.food = instanceItem("Base.Chocolate")
            p.drink = instanceItem("Base.Milk")
            p.cont:AddItem(p.food)
            p.cont:AddItem(p.drink)
            PF.patchItem(p.food, false)
            PF.ageDrink(p.drink, false)
        end
    end)
    t.queue(1, function()
        t.jumpDays(100)
        for _, p in ipairs(ctx.places) do
            p.food:updateAge()
            PF.ageDrink(p.drink, false)
            local elapsed = PF.worldDays() - ctx.t0
            local foodAge, drinkAge = p.food:getAge(), p.drink:getModData().PF_age or -1
            local want = elapsed * p.expect
            t.check(string.format("food in the %s ages x%.2f (engine)", p.name, p.expect), math.abs(foodAge - want) < 1.5,
                string.format("age=%.2f expected about %.2f", foodAge, want))
            t.check(string.format("drink in the %s ages x%.2f (mod)", p.name, p.expect), math.abs(drinkAge - want) < 1.5,
                string.format("age=%.2f expected about %.2f", drinkAge, want))
        end
        local fridge = nil
        for _, p in ipairs(ctx.places) do if p.name == "fridge" then fridge = p end end
        if fridge then
            t.check("milk 100 days in a fridge is still good (limit 60 at room speed)", fluidName(fridge.drink) == "CowMilk", fluidName(fridge.drink))
        end
        for _, p in ipairs(ctx.places) do
            if p.name == "room" then t.check("milk 100 days in a room has spoiled", fluidName(p.drink) == "SpoiledDrink", fluidName(p.drink)) end
        end
        t.finish()
    end)
end

