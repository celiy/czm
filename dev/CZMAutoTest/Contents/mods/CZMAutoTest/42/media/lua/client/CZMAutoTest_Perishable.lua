    end)
end

CZM_TEST_SUITES.perishable = function(t)
    local PF = PerishableFoods
    local ctx = {}
    local function fluidOf(item)
        local fc = item:getFluidContainerFromSelfOrWorldItem()
        return fc and fc:getPrimaryFluid() and tostring(fc:getPrimaryFluid():getFluidTypeString()) or "-"
    end
    local function newDrink(name)
        local item = instanceItem(name)
        return item
    end

    -- ---- food that exists in a save
    t.queue(1, function()
        t.check("perishable mod loaded", PF ~= nil and PF.patchItem ~= nil and PF.ageDrink ~= nil)
        local sc = getScriptManager():getItem("Base.Chocolate")
        t.check("script values applied (Chocolate DaysFresh 365)", sc ~= nil and sc:getDaysFresh() == 365,
            string.format("DaysFresh=%s", tostring(sc and sc:getDaysFresh())))
        t.check("applied to all scheduled items", PF.missingCount == 0, string.format("applied=%s missing=%s", tostring(PF.appliedCount), tostring(PF.missingCount)))
        ctx.choc = instanceItem("Base.Chocolate")
        ctx.cheese = instanceItem("Base.Cheese")
        ctx.sugar = instanceItem("Base.Sugar")
        ctx.oldChoc = instanceItem("Base.Chocolate")
        ctx.oldChoc:setAge(400)
        ctx.inv = getSpecificPlayer(0):getInventory()
        ctx.inv:AddItem(ctx.choc)
    end)
    t.queue(1, function()
        local changed = PF.patchItem(ctx.choc, false)
        t.check("new chocolate gets its shelf life", changed and ctx.choc:getOffAge() == 365 and ctx.choc:getOffAgeMax() == 420,
            string.format("offAge=%s offAgeMax=%s", tostring(ctx.choc:getOffAge()), tostring(ctx.choc:getOffAgeMax())))
        t.check("new chocolate starts fresh (age 0)", ctx.choc:getAge() == 0, string.format("age=%.2f", ctx.choc:getAge()))
        t.check("second patch is a no-op", PF.patchItem(ctx.choc, false) == false)
        PF.patchItem(ctx.oldChoc, false)
        t.check("existing old item is reset to fresh, not rotten", ctx.oldChoc:getAge() == 0 and ctx.oldChoc:getOffAge() == 365,
            string.format("age=%.2f offAge=%s", ctx.oldChoc:getAge(), tostring(ctx.oldChoc:getOffAge())))
        PF.patchItem(ctx.cheese, false)
        local cheeseScript = getScriptManager():getItem("Base.Cheese") -- another mod may change cheese: compare with its own script
        t.check("item with its own script values is left alone", ctx.cheese:getOffAge() == cheeseScript:getDaysFresh() and ctx.cheese:getOffAgeMax() == cheeseScript:getDaysTotallyRotten(),
            string.format("offAge=%s script=%s", tostring(ctx.cheese:getOffAge()), tostring(cheeseScript:getDaysFresh())))
        PF.patchItem(ctx.sugar, false)
        t.check("sugar (never spoils) is left alone", ctx.sugar:getOffAge() >= 1000000000)
    end)

    -- ---- food generated by the world is already aged
    t.queue(1, function()
        t.jumpDays(50)
        ctx.bisc = instanceItem("Base.CookiesOatmeal")
        PF.patchItem(ctx.bisc, true)
        local expected = PF.worldGeneratedAge()
        t.check("world-generated biscuit is already aged by the clock", math.abs(ctx.bisc:getAge() - expected) < 0.05 and expected > 40,
            string.format("age=%.2f expected=%.2f offAgeMax=%s", ctx.bisc:getAge(), expected, tostring(ctx.bisc:getOffAgeMax())))
        t.check("world-generated biscuit is past its 45-day limit", ctx.bisc:getAge() > ctx.bisc:getOffAgeMax())
        ctx.chocWorld = instanceItem("Base.Chocolate")
        PF.patchItem(ctx.chocWorld, true)
        t.check("world-generated chocolate is still fresh after 50 days", ctx.chocWorld:getAge() < ctx.chocWorld:getOffAge())
    end)

    -- ---- drinks: own clock, spoil into Spoiled Drink
    t.queue(1, function()
        ctx.milk = newDrink("Base.Milk")
        ctx.wine = newDrink("Base.Wine")
        ctx.wineOpen = newDrink("Base.WineOpen")
        ctx.whiskey = newDrink("Base.Whiskey")
        ctx.pop = newDrink("Base.Pop")
        ctx.milkAmount = ctx.milk:getFluidContainer():getAmount()
        PF.ageDrink(ctx.milk, false)
        PF.ageDrink(ctx.wine, false)
        PF.ageDrink(ctx.wineOpen, false)
        PF.ageDrink(ctx.whiskey, false)
        PF.ageDrink(ctx.pop, false)
        t.check("new milk starts fresh", (ctx.milk:getModData().PF_age or -1) == 0)
        t.check("sealed wine has no clock (never spoils)", ctx.wine:getModData().PF_t == nil)
        t.check("whiskey has no clock (never spoils)", ctx.whiskey:getModData().PF_t == nil)
        t.check("opened wine has a clock", ctx.wineOpen:getModData().PF_t ~= nil)
    end)
    t.queue(1, function()
        t.jumpDays(30)
        PF.ageDrink(ctx.milk, false)
        t.check("milk is fine after 30 days (limit 60)", fluidOf(ctx.milk) == "CowMilk", fluidOf(ctx.milk))
        t.jumpDays(31)
        PF.ageDrink(ctx.milk, false)
        t.check("milk spoils after 60 days", fluidOf(ctx.milk) == "SpoiledDrink", fluidOf(ctx.milk))
        t.check("spoiled milk keeps its amount", math.abs(ctx.milk:getFluidContainer():getAmount() - ctx.milkAmount) < 0.01,
            string.format("%.2f of %.2f", ctx.milk:getFluidContainer():getAmount(), ctx.milkAmount))
        PF.ageDrink(ctx.wineOpen, false)
        t.check("opened wine has spoiled after 61 days (limit 14)", fluidOf(ctx.wineOpen) == "SpoiledDrink", fluidOf(ctx.wineOpen))
        PF.ageDrink(ctx.wine, false)
        PF.ageDrink(ctx.whiskey, false)
        t.check("sealed wine and whiskey are untouched", fluidOf(ctx.wine) == "Wine" and fluidOf(ctx.whiskey) == "Whiskey")
        PF.ageDrink(ctx.pop, false)
        t.check("pop is fine after 61 days (limit 365)", fluidOf(ctx.pop) ~= "SpoiledDrink", fluidOf(ctx.pop))
    end)

    -- ---- fridge and freezer
    t.queue(1, function()
        local function fake(fridge, freezer, powered)
            return { isFridge = function() return fridge end, isFreezer = function() return freezer end,
                getSourceGrid = function() return powered and { haveElectricity = function() return true end } or { haveElectricity = function() return false end } end }
        end
        local saveShut = SandboxVars.ElecShutModifier
        SandboxVars.ElecShutModifier = -1
        t.check("normal room: normal speed", PF.rateFor(fake(false, false, true)) == 1)
        t.check("powered fridge slows spoilage", math.abs(PF.rateFor(fake(true, false, true)) - PF.fridgeFactor()) < 0.001 and PF.fridgeFactor() < 1,
            string.format("%.2f", PF.rateFor(fake(true, false, true))))
        t.check("powered freezer stops spoilage", PF.rateFor(fake(false, true, true)) == 0)
        t.check("unpowered fridge does not help", PF.rateFor(fake(true, false, false)) == 1)
        SandboxVars.ElecShutModifier = saveShut
    end)
    t.queue(1, function()
        -- a drink in a fridge ages slowly: age through a container that reports a powered fridge
        local milk = newDrink("Base.Milk")
        PF.ageDrink(milk, false)
        local original = PF.rateFor
        PF.rateFor = function() return 0.2 end
        t.jumpDays(100)
        PF.ageDrink(milk, false)
        PF.rateFor = original
        t.check("milk 100 days in a fridge (x0.2) is only 20 days old and fresh",
            math.abs((milk:getModData().PF_age or -1) - 20) < 0.5 and fluidOf(milk) == "CowMilk",
            string.format("age=%.2f fluid=%s", milk:getModData().PF_age or -1, fluidOf(milk)))
    end)

    -- ---- world-generated drink catches up from the clock start
    t.queue(1, function()
        local milk = newDrink("Base.Milk")
        PF.ageDrink(milk, true)
        t.check("world-generated milk is already past its limit", fluidOf(milk) == "SpoiledDrink", fluidOf(milk))
        local pop = newDrink("Base.Pop")
        PF.ageDrink(pop, true)
        t.check("world-generated pop is still fine", fluidOf(pop) ~= "SpoiledDrink", fluidOf(pop))
    end)

    -- ---- sandbox options
    t.queue(1, function()
        local o = SandboxVars.PerishableFoods
        t.check("sandbox options reach the mod", o ~= nil and o.ShelfLifeMultiplier == 100, o and tostring(o.ShelfLifeMultiplier) or "no SandboxVars")
        o.ShelfLifeMultiplier = 200
        t.check("live multiplier doubles a shelf life", math.abs(PF.drinkShelfLife(instanceItem("Base.Milk")) - 120) < 0.01,
            string.format("%.1f", PF.drinkShelfLife(instanceItem("Base.Milk"))))
        PF.applySchedule()
        local sc = getScriptManager():getItem("Base.Chocolate")
        t.check("multiplier scales food scripts too", sc:getDaysFresh() == 730, tostring(sc:getDaysFresh()))
        o.ShelfLifeMultiplier = 100
        PF.applySchedule()
        o.Enabled = false
        local milk = newDrink("Base.Milk")
        PF.processItem(milk, true)
        t.check("disabled: nothing happens", milk:getModData().PF_t == nil)
        o.Enabled = true
    end)

    -- ---- a drink in the player's inventory is handled with its container
    t.queue(1, function()
        local inv = getSpecificPlayer(0):getInventory()
        local juice = newDrink("Base.JuiceOrange")
        inv:AddItem(juice)
        PF.processContainer(inv, false)
        t.check("a drink in the inventory gets its clock", juice:getModData().PF_t ~= nil)
        t.finish()
    end)
end

