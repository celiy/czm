--[[
    Perishable Foods: Vanilla Foods Expanded - add-on.

    Adds the shelf lives of Vanilla Foods Expanded foods and drinks to the
    tables of Perishable Foods (PerishableFoods.SCHEDULE for foods,
    PerishableFoods.DRINKS for fluid containers) and applies them. Everything
    else (aging, fridges, spoiled drinks, the sandbox multiplier) is the main
    mod's code. The data is in PFVFX_Data.lua, generated by tools/generate_vfx.py.
]]

require "PerishableFoods/PF_Core"
require "PerishableFoods/PF_Data"
require "PerishableFoods/PF_Drinks"
require "PerishableFoods/PF_Scripts"
require "PerishableFoodsVFX/PFVFX_Data"

local PF = PerishableFoods
local VFX = PerishableFoodsVFX

if not VFX.merged then
    VFX.merged = true
    local known = {}
    for _, entry in ipairs(PF.SCHEDULE) do known[entry[1]] = true end
    local foods = 0
    for _, entry in ipairs(VFX.FOODS) do
        if not known[entry[1]] then
            PF.SCHEDULE[#PF.SCHEDULE + 1] = { entry[1], entry[2], entry[3] }
            foods = foods + 1
        end
    end
    local drinks = 0
    for fullType, entry in pairs(VFX.DRINKS) do
        if PF.DRINKS[fullType] == nil then
            PF.DRINKS[fullType] = entry
            drinks = drinks + 1
        end
    end
    VFX.addedFoods, VFX.addedDrinks = foods, drinks
    print(string.format("[PerishableFoodsVFX] added %d foods and %d drinks to the shelf life tables", foods, drinks))
end

-- Apply the new entries now; the main mod applies the whole table again when a game starts.
PF.applySchedule()
