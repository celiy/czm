--[[
    Gasoline Degradation - core

    How it works
    ------------
    Gasoline decays continuously: every day each container loses the same
    share of whatever it holds (exponential decay). DaysToFullDegradation is
    how long it takes to drop to 5% of what it had, so with the default 200
    days a full 10 L can holds ~6.4 L after 1 month, ~2.6 L after 3 months
    and 0.5 L after 200 days. The rate never depends on the date: gasoline
    found or poured on day 300 decays exactly like gasoline on day 1.

    Time is measured in "degradation days": days since the mod first ran in
    this save (the game start in a new game, the day it was added in an
    existing one) minus the StartDay option.

    Safe to add or remove mid-save: adding starts the clock at that moment
    (nothing is retroactively degraded); removing leaves only small unused
    modData keys (GD_t, GD_acc, GD_frac) behind. Gasoline already lost is not
    restored.

    Every object that holds gasoline (item, vehicle tank, gas pump) keeps the
    degradation day it was last updated on in its modData (GD_t). Whenever we
    look at it again we multiply its gasoline by decayFactor(now - GD_t).
    Because the decay is exponential it does not matter how often an object
    is checked, or whether its chunk was unloaded for weeks: the result is
    the same as if it had been ticking the whole time, and nothing has to
    run for parts of the map nobody is in.

    Objects never seen before:
      * generated by the world (vehicles, gas pumps, loot spawned into
        containers) are caught up from the start of the clock, as if they had
        been degrading since the game began: a car in a corner of the map
        nobody visited until day 100 already holds what 100 days of decay
        leave. When the mod is added mid-save the clock starts at that day, so
        nothing is retroactively degraded;
      * anything the player may have touched (carried or dropped cans, loot
        window containers, placed barrels) is only stamped, so gasoline the
        player moved around is never degraded twice.

    Recent access delay: vehicles, pumps and world containers the player
    interacted with keep their gasoline for AccessDelayDays more days.
    Gasoline carried in a player's inventory (or bags) does not degrade at
    all while carried, and keeps the same delay after it is put down.

    Objects at or below the minimum liters option are left alone, and
    degradation never takes an object below that minimum.
]]

GasolineDegradation = GasolineDegradation or {}
local GD = GasolineDegradation

GD.KEY = "GD_t"          -- modData key: degradation day of the last update
GD.FRAC_KEY = "GD_frac"  -- modData key: fractional liters for gas pumps (stored as integers)
GD.DEBUG = false

local EPSILON = 0.0001

local function log(...)
    if GD.DEBUG then print("[GasolineDegradation]", ...) end
end
GD.log = log

function GD.options()
    return SandboxVars.GasolineDegradation or {}
end

function GD.isEnabled()
    return GD.options().Enabled ~= false
end

function GD.containerMin()
    return GD.options().ContainerMinLiters or 0.5
end

function GD.vehicleMin()
    return GD.options().VehicleMinLiters or 1.0
end

-- World day on which the mod first ran in this save. In a new game that is
-- ~0, so everything degrades from the start. When the mod is added to an
-- existing save it is the current day, so the clock starts "now" and nothing
-- is retroactively degraded. Stored in the save's global mod data.
function GD.originDay()
    if GD._origin then return GD._origin end
    local data = ModData.getOrCreate("GasolineDegradation")
    if data.origin == nil then
        data.origin = getGameTime():getWorldAgeHours() / 24
    end
    GD._origin = data.origin
    return GD._origin
end

-- Degradation days elapsed (never negative).
function GD.elapsedDays()
    local d = getGameTime():getWorldAgeHours() / 24 - GD.originDay() - (GD.options().StartDay or 0)
    if d < 0 then return 0 end
    return d
end

-- Gasoline left after `days` of degradation drops to this share of what
-- there was (5%: a full 10 L can ends at 0.5 L).
GD.LIFETIME_SHARE = 0.05

-- Share of an object's gasoline still left after `days` of degradation.
-- Exponential decay: every day the same fraction of whatever is left is
-- lost, so it only depends on how long the gasoline sat, never on the date.
-- With the default 200 days a full 10 L can holds ~6.4 L after 1 month,
-- ~2.6 L after 3 months and 0.5 L after 200 days.
function GD.decayFactor(days)
    if days <= 0 then return 1 end
    local lifetime = GD.options().DaysToFullDegradation or 200
    if lifetime <= 0 then return 0 end
    return GD.LIFETIME_SHARE ^ (days / lifetime)
end

----------------------------------------------------------------------------
-- Recent access delay
--
-- A vehicle, pump or world container the player interacted with keeps its
-- gasoline for AccessDelayDays more days. The holder (vehicle / pump / the
-- object that owns the container) stores the world day of the last access in
-- its modData (GD_acc). Callers settle the object's degradation *before*
-- touching it, so the time before the access has already been applied and
-- only the delay window has to be skipped.
----------------------------------------------------------------------------

GD.ACCESS_KEY = "GD_acc"

function GD.accessDelayEnabled()
    return GD.options().AccessDelay ~= false
end

function GD.accessDelayDays()
    return GD.options().AccessDelayDays or 14
end

-- Record an interaction. `holderMd` is the modData of the vehicle, pump or
-- object that owns the container (see GD.holderModData).
function GD.touch(holderMd)
    if holderMd and GD.accessDelayEnabled() then
        holderMd[GD.ACCESS_KEY] = getGameTime():getWorldAgeHours() / 24
    end
end

-- Degradation day on which the delay window of this holder ends, or nil.
function GD.delayEnd(holderMd)
    if not holderMd or not GD.accessDelayEnabled() then return nil end
    local acc = holderMd[GD.ACCESS_KEY]
    if acc == nil then return nil end
    return acc + GD.accessDelayDays() - GD.originDay() - (GD.options().StartDay or 0)
end

-- The container an item container finally sits in: bags are followed out
-- to what holds them. Returns nil when the chain is broken (e.g. on the floor).
function GD.outerContainer(container)
    if not container then return nil end
    for _ = 1, 5 do
        local bag = container:getContainingItem()
        if not bag then break end
        local outer = bag:getContainer()
        if not outer then return nil end
        container = outer
    end
    return container
end

-- True when the container (or the bag it is in) is carried by a character.
function GD.isCarried(container)
    local outer = GD.outerContainer(container)
    return outer ~= nil and outer:getCharacter() ~= nil
end

-- modData of whatever owns an ItemContainer, for the access delay. Carried
-- containers have no holder: each carried item is its own holder instead
-- (see GD.processItem).
function GD.holderModData(container)
    container = GD.outerContainer(container)
    if not container then return nil end
    if container:getCharacter() then return nil end
    local part = container:getVehiclePart()
    if part then
        local vehicle = part:getVehicle()
        return vehicle and vehicle:getModData() or nil
    end
    local parent = container:getParent()
    if parent then return parent:getModData() end
    return nil
end

--[[
    Decide the new gasoline amount for one object and update its stamp.
    md        : the object's modData table
    amount    : liters of gasoline it holds now
    minLiters : never degrade below this, ignore objects at or below it
    now       : current degradation day (GD.elapsedDays())
    stampOnly : for an object never seen before, only stamp it (no catch-up)
    holderMd  : modData holding the last-access day, or nil (no delay)
    Returns the new amount, or nil when nothing should change.
]]
function GD.computeNew(md, amount, minLiters, now, stampOnly, holderMd)
    local last = md[GD.KEY]
    if last == nil then
        if stampOnly then
            md[GD.KEY] = now
            return nil
        end
        last = 0 -- world-generated: degrading since the start of the clock
    elseif now < last then
        -- StartDay may have been raised mid-save; keep the stamp sane.
        md[GD.KEY] = now
        return nil
    end

    -- Skip the recent-access delay window.
    local from = last
    local delayEnd = GD.delayEnd(holderMd)
    if delayEnd and delayEnd > from then from = delayEnd end
    if now <= from then return nil end -- still inside the delay window

    md[GD.KEY] = now
    if amount <= minLiters then return nil end

    local ratio = GD.decayFactor(now - from)
    if ratio >= 1 then return nil end

    local new = amount * ratio
    if new < minLiters then new = minLiters end
    if amount - new < EPSILON then return nil end
    return new
end

----------------------------------------------------------------------------
-- Items (anything with a fluid container holding Fluid.Petrol, modded too)
----------------------------------------------------------------------------

function GD.processItem(item, now, stampOnly, holderMd, carried)
    -- The "or world item" getter also works for items lying on the floor,
    -- where the plain getter returns nothing.
    local fc = item:getFluidContainerFromSelfOrWorldItem()
    if not fc or fc:isEmpty() then return end

    local petrol = fc:getSpecificFluidAmount(Fluid.Petrol)
    if petrol <= 0 then return end

    -- Gasoline carried by a player does not degrade: each carried item is
    -- touched every time it is processed, so its delay window keeps moving
    -- and only runs out once the item has been out of inventories for the
    -- delay length.
    local itemMd = item:getModData()
    if carried then
        holderMd = itemMd
    elseif itemMd[GD.ACCESS_KEY] and (not holderMd
            or (holderMd[GD.ACCESS_KEY] or -1) < itemMd[GD.ACCESS_KEY]) then
        -- Recently carried: the item's own delay still applies.
        holderMd = itemMd
    end

    local new = GD.computeNew(itemMd, petrol, GD.containerMin(), now, stampOnly, holderMd)
    if carried then GD.touch(itemMd) end
    if not new then return end

    -- Only the gasoline is reduced; other fluids in a mixture are untouched.
    fc:adjustSpecificFluidAmount(Fluid.Petrol, new)
    if isServer() then
        item:syncItemFields()
        sendItemStats(item)
    end
    if GD.DEBUG then log("item", item:getFullType(), string.format("%.2f -> %.2f L", petrol, new)) end
end

-- Processes every item in a container, including items inside bags.
function GD.processContainer(container, now, stampOnly, depth, holderMd, carried)
    depth = depth or 0
    if not container or depth > 4 then return end
    if depth == 0 then
        holderMd = GD.holderModData(container)
        carried = GD.isCarried(container)
    end
    local items = container:getItems()
    for i = 0, items:size() - 1 do
        local item = items:get(i)
        GD.processItem(item, now, stampOnly, holderMd, carried)
        if instanceof(item, "InventoryContainer") then
            GD.processContainer(item:getInventory(), now, stampOnly, depth + 1, holderMd, carried)
        end
    end
end

----------------------------------------------------------------------------
-- Vehicles (any part that is a container of "Gasoline", modded cars too)
----------------------------------------------------------------------------

function GD.processVehicle(vehicle, now)
    for i = 0, vehicle:getPartCount() - 1 do
        local part = vehicle:getPartByIndex(i)
        if part and part:isContainer() and part:getContainerContentType() == "Gasoline" then
            local amount = part:getContainerContentAmount()
            local new = GD.computeNew(part:getModData(), amount, GD.vehicleMin(), now, false, vehicle:getModData())
            if new then
                part:setContainerContentAmount(new)
                vehicle:transmitPartModData(part)
                if GD.DEBUG then log("vehicle", vehicle:getScriptName(), string.format("%.2f -> %.2f L", amount, new)) end
            end
        end
    end
end

----------------------------------------------------------------------------
-- World objects: gas pumps and placed fluid containers (barrels, etc.)
----------------------------------------------------------------------------

function GD.isGasPump(obj)
    local props = obj:getProperties()
    return props ~= nil and props:has("fuelAmount")
end

function GD.processGasPump(obj, now)
    if SandboxVars.FuelStationGasInfinite then return end
    if GD.options().AffectGasPumps == false then return end

    local md = obj:getModData()
    -- Pumps roll their fuel the first time someone uses them. Until then
    -- there is nothing to degrade; once rolled, it is caught up from the
    -- start of the clock like any other world-generated gasoline.
    local stored = md.fuelAmount
    if type(stored) ~= "number" then return end

    local amount = stored + (md[GD.FRAC_KEY] or 0)
    local new = GD.computeNew(md, amount, GD.containerMin(), now, false, md)
    if not new then return end

    -- Pumps store whole liters; keep the remainder so small steps add up.
    -- (rounded so the minimum liters is never undercut: 0.5 L keeps 1 L)
    local whole = math.max(math.floor(new), math.ceil(GD.containerMin()))
    md[GD.FRAC_KEY] = new - whole
    obj:setPipedFuelAmount(whole)
    if GD.DEBUG then log("pump", obj:getX(), obj:getY(), string.format("%.2f -> %d L", amount, whole)) end
end

-- Placed objects with a fluid container (barrels, modded tanks...).
-- These are filled by players, so a first sighting only stamps them.
function GD.processWorldFluid(obj, now)
    local fc = obj:getFluidContainer()
    if not fc or fc:isEmpty() then return end
    local petrol = fc:getSpecificFluidAmount(Fluid.Petrol)
    if petrol <= 0 then return end

    local new = GD.computeNew(obj:getModData(), petrol, GD.containerMin(), now, true, obj:getModData())
    if not new then return end
    fc:adjustSpecificFluidAmount(Fluid.Petrol, new)
    if isServer() then obj:sync() end
    if GD.DEBUG then log("world fluid", obj:getX(), obj:getY(), string.format("%.2f -> %.2f L", petrol, new)) end
end

-- True when the square holds something we need to keep checking.
function GD.processSquare(square, now)
    local relevant = false
    local objects = square:getObjects()
    for i = 0, objects:size() - 1 do
        local obj = objects:get(i)
        if GD.isGasPump(obj) then
            relevant = true
            GD.processGasPump(obj, now)
        elseif instanceof(obj, "IsoWorldInventoryObject") then
            -- Items lying on the floor (gas cans, bottles...).
            local item = obj:getItem()
            local fc = item and item:getFluidContainerFromSelfOrWorldItem()
            if fc and fc:contains(Fluid.Petrol) then
                relevant = true
                GD.processItem(item, now, true) -- may have been dropped by a player
            end
        elseif obj:getFluidContainer() then
            relevant = true
            GD.processWorldFluid(obj, now)
        end
    end
    return relevant
end

----------------------------------------------------------------------------
-- Interactions: settle first, then record the access
----------------------------------------------------------------------------

function GD.touchVehicle(vehicle)
    if not vehicle or not GD.accessDelayEnabled() then return end
    GD.processVehicle(vehicle, GD.elapsedDays())
    GD.touch(vehicle:getModData())
end

function GD.touchPump(obj)
    if not obj or not GD.accessDelayEnabled() then return end
    GD.processGasPump(obj, GD.elapsedDays())
    GD.touch(obj:getModData())
end

function GD.touchContainer(container)
    if not container or not GD.accessDelayEnabled() then return end
    local holderMd = GD.holderModData(container)
    if not holderMd then return end
    GD.processContainer(container, GD.elapsedDays(), true)
    GD.touch(holderMd)
end
